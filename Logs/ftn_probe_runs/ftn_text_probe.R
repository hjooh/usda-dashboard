library(shinytest2)
Sys.setenv(NOT_CRAN = "true")
app <- AppDriver$new(app_dir='.', name='ftn_text_probe', load_timeout=120000, timeout=120000)
on.exit(app$stop(), add=TRUE)
txt <- app$get_js("(function(){ var t = (document.body && document.body.innerText) ? document.body.innerText : ''; return String(t); })();")
ids <- app$get_js("(function(){ var nodes=document.querySelectorAll('[id]'); var out=[]; for (var i=0;i<nodes.length;i++){ if(nodes[i].id) out.push(nodes[i].id);} return out.slice(0,160).join('|'); })();")
cat('BODY_TEXT_START\n')
cat(substr(as.character(txt), 1, 5000))
cat('\nBODY_TEXT_END\n')
cat('ID_SAMPLE=', as.character(ids), '\n', sep='')
